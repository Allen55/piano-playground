import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import { tmpdir } from "node:os";
import { join } from "node:path";

const browser = await chromium.launch({ executablePath:"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe", headless:true, args:["--no-sandbox"] });
const errors=[];
try {
  const desktop=await browser.newPage({viewport:{width:1600,height:1000}});
  desktop.on("pageerror",error=>errors.push(error.message));
  await desktop.goto("http://127.0.0.1:3000",{waitUntil:"networkidle"});
  assert.match(await desktop.locator(".key-title").textContent(),/G major/);
  assert.match(await desktop.locator(".chord-symbol").textContent(),/Cmaj7/);
  await desktop.getByRole("button",{name:/Golden Thread/}).click();
  assert.match(await desktop.locator(".chord-symbol").textContent(),/Gmaj9/);
  await desktop.locator(".timeline-card").nth(1).click();
  assert.match(await desktop.locator(".chord-symbol").textContent(),/Em9/);
  await desktop.getByRole("button",{name:/1st inversion/}).click();
  assert.match(await desktop.locator(".panel-badge").textContent(),/1st inversion/);
  await desktop.getByRole("button",{name:"Compare chords"}).click();
  assert.equal(await desktop.locator(".comparison-card").count(),4);
  assert.match(await desktop.locator(".comparison-card").nth(1).textContent(),/Em9/);
  assert.match(await desktop.locator(".comparison-card").nth(1).textContent(),/1st inversion/);
  await desktop.getByRole("button",{name:"Play Gmaj9"}).click();
  await desktop.getByRole("button",{name:/Select Cmaj9, chord 3/}).click();
  assert.match(await desktop.locator(".chord-symbol").textContent(),/Cmaj9/);
  await desktop.getByRole("button",{name:"Single keyboard"}).click();
  assert.equal(await desktop.locator(".comparison-card").count(),0);
  await desktop.getByRole("button",{name:"Hear chord"}).click();
  await desktop.locator(".play-main").click();
  assert.match(await desktop.locator(".now-playing").textContent(),/PLAYING/);
  await desktop.locator(".play-main").click();
  await desktop.getByRole("button",{name:/Split hands/}).click();
  assert.equal(await desktop.locator(".split-keyboards .piano-svg").count(),2);
  await desktop.getByRole("button",{name:/Split hands/}).click();
  await desktop.locator(".left-sidebar .field-row select").nth(1).selectOption("minor");
  assert.match(await desktop.locator(".key-title").textContent(),/E minor/);
  await desktop.getByRole("button",{name:/Optimize voice leading/}).click();
  assert.equal(await desktop.locator(".timeline-card").count(),4);
  await desktop.getByRole("button",{name:"Compare chords"}).click();
  assert.match(await desktop.locator(".comparison-card").first().textContent(),/Em9/);
  assert.equal(await desktop.locator(".comparison-card .comparison-keyboard").count(),4);
  await desktop.getByRole("button",{name:"Save",exact:true}).click();
  await desktop.getByPlaceholder("E minor study").fill("E minor colors");
  await desktop.getByRole("button",{name:"Save progression"}).click();
  assert.match(await desktop.locator(".saved-item").first().textContent(),/E minor colors/);
  await desktop.screenshot({path:join(tmpdir(),"keyframe-desktop.png")});

  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  mobile.on("pageerror",error=>errors.push(error.message));
  await mobile.goto("http://127.0.0.1:3000",{waitUntil:"networkidle"});
  await mobile.getByRole("button",{name:"Compare chords"}).click();
  assert.equal(await mobile.locator(".comparison-card").count(),4);
  const sizing=await mobile.evaluate(()=>({viewport:window.innerWidth,scroll:document.documentElement.scrollWidth,hero:document.querySelector(".chord-hero")?.getBoundingClientRect().width}));
  await mobile.screenshot({path:join(tmpdir(),"keyframe-mobile.png")});
  assert.ok(sizing.scroll<=sizing.viewport+1,`mobile overflow ${JSON.stringify(sizing)}`);
  await mobile.getByRole("button",{name:"Open menu"}).click();
  assert.equal(await mobile.locator(".left-sidebar").evaluate(el=>el.classList.contains("mobile-open")),true);
  await mobile.getByRole("button",{name:/Blue Hour/}).click();
  assert.match(await mobile.locator(".chord-symbol").textContent(),/Am7/);
  assert.deepEqual(errors,[]);
  console.log("Desktop and mobile interactions passed.",sizing);
} finally { await browser.close(); }
